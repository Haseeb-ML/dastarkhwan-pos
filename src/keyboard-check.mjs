import { chromium, expect } from '@playwright/test'
const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:1366,height:768}})
await page.goto('http://localhost:5173')
await page.locator('input[type=text]').fill('owner')
await page.locator('input[type=password]').fill('Demo@2026!')
await page.locator('form button.primary').click()
await page.locator('.sidebar').waitFor()
await page.locator('.sidebar nav button').nth(2).click()
await page.getByRole('button', {name:'کھانا تبدیل کریں',exact:true}).first().click()
const field = page.locator('.modal-backdrop input').first()
const original = await field.inputValue()
await page.locator('.modal-backdrop').getByRole('button',{name:'Open Urdu keyboard'}).first().click()
await expect(page.getByRole('textbox',{name:'Urdu keyboard text'})).toHaveValue(original)
await page.locator('.uk-tools button').last().click()
await page.getByRole('textbox',{name:'Urdu keyboard text'}).pressSequentially('ckn')
await expect(page.getByRole('textbox',{name:'Urdu keyboard text'})).toHaveValue('چکن')
await page.locator('.uk-words button').filter({hasText:'کڑاہی'}).click()
await page.screenshot({path:'output/keyboard-desktop.png'})
await page.locator('.uk-done').click()
await expect(field).toHaveValue('چکن کڑاہی ')
await page.locator('.modal-backdrop').getByRole('button',{name:'Open Urdu keyboard'}).first().click()
await page.locator('.uk-tools button').last().click()
await page.getByRole('button',{name:'Close Urdu keyboard',exact:true}).click()
await expect(field).toHaveValue('چکن کڑاہی ')
await page.setViewportSize({width:390,height:844})
await page.locator('.modal-backdrop').getByRole('button',{name:'Open Urdu keyboard'}).first().click()
const bounds = await page.locator('.uk-panel').boundingBox()
if(bounds.x < 0 || bounds.x + bounds.width > 390 || bounds.y < 0 || bounds.y + bounds.height > 844) throw Error('Popup exceeds viewport')
await page.screenshot({path:'output/keyboard-mobile.png'})
console.log('PASS: physical Urdu typing, quick words, OK transfer, cancel preservation, mobile bounds')
await browser.close()
